/** Integration checks against in-memory backend. Production requires Supabase/WebRTC E2E. */
import assert from 'node:assert/strict';
import * as Hub from '../server/hub-service.js';
import * as Platform from '../server/platform-service.js';
const owner={id:'TDB-TEST-OWNER',username:'Organizador'},guest={id:'TDB-TEST-GUEST',username:'Convidado'},third={id:'TDB-TEST-3',username:'Terceiro'},fourth={id:'TDB-TEST-4',username:'Quarto'};
const {code}=await Hub.createRoom(owner,{name:'TDB Teste Integrado',visibility:'public'});
for(const u of [guest,third,fourth])await Hub.joinRoom(code,u);
await Hub.act(code,owner,{type:'room:settings',tables:'owner',music:{play:'owner',add:'everyone'},voteSkip:true});
await assert.rejects(Hub.act(code,guest,{type:'table:create',game:'chess'}),/permissão/i);
await assert.rejects(Hub.act(code,guest,{type:'music',action:{type:'play'}}),/restringiu/i);
await Hub.act(code,owner,{type:'room:allow-table',userId:guest.id,allow:true});
await Hub.act(code,owner,{type:'room:settings',tables:'approved'});
const tr=(await Hub.act(code,guest,{type:'table:create',game:'truco',settings:{seats:4,spectators:'approval',turnTimer:30}})).table;
await Hub.act(code,guest,{type:'table:bot',tableId:tr.id,difficulty:'easy'});
await Hub.act(code,guest,{type:'table:bot',tableId:tr.id,difficulty:'medium'});
await Hub.act(code,guest,{type:'table:bot',tableId:tr.id,difficulty:'hard'});
await Hub.act(code,guest,{type:'table:swap',tableId:tr.id,a:0,b:2});
await Hub.act(code,guest,{type:'table:start',tableId:tr.id});
let snap=await Hub.getSnapshot(code,guest,tr.id);
assert.equal(snap.game.players.length,4);
assert.equal(snap.room.tables.find(t=>t.id===tr.id).settings.seats,4);
await assert.rejects(Hub.getSnapshot(code,owner,tr.id),/autorização/i);
await Hub.act(code,owner,{type:'table:watch',tableId:tr.id});
await assert.rejects(Hub.getSnapshot(code,owner,tr.id),/autorização/i);
await Hub.act(code,guest,{type:'table:approve',tableId:tr.id,userId:owner.id});
snap=await Hub.getSnapshot(code,owner,tr.id);
assert.equal(snap.game.role,'spectator');
await Hub.act(code,guest,{type:'table:unwatch',tableId:tr.id,userId:owner.id});
await assert.rejects(Hub.getSnapshot(code,owner,tr.id),/autorização/i);
await Hub.act(code,owner,{type:'table:watch',tableId:tr.id});
await Hub.act(code,guest,{type:'table:approve',tableId:tr.id,userId:owner.id});
snap=await Hub.getSnapshot(code,owner,tr.id);
for(const hand of Object.values(snap.game.hands))assert(hand.every(card=>card===null),'Truco leaked private hand');
const {code:trainCode,tableId:chessTable}=await Hub.startTraining(owner,{game:'chess',difficulty:'hard'});
const training=await Hub.getSnapshot(trainCode,owner,chessTable);
assert.equal(training.room.training,true);
assert.equal(training.game.game,'chess');
assert.equal(training.room.tables[0].players.filter(p=>p.bot).length,1);
await assert.rejects(Hub.joinRoom(trainCode,guest),/pessoal/i);
await Hub.act(code,owner,{type:'music',action:{type:'add',url:'https://youtu.be/dQw4w9WgXcQ'}});
await Platform.musicProfileAction(guest,{type:'SAVE_PRESET',roomCode:code,name:'Playlist particular'});
const personal=await Platform.musicProfile(guest);
assert.equal(personal.presets[0].tracks.length,1);
await Platform.musicProfileAction(guest,{type:'APPLY_PRESET',roomCode:code,presetId:personal.presets[0].id});
assert.equal((await Hub.getSnapshot(code,owner)).room.music.queue.length,2);
for(const u of [owner,guest,third])await Hub.act(code,u,{type:'screen:start'});
assert.equal((await Hub.getSnapshot(code,owner)).room.screens.length,3);
await assert.rejects(Hub.act(code,fourth,{type:'screen:start'}),/três transmissões/i);
const bScreen=(await Hub.getSnapshot(code,owner)).room.screens.find(s=>s.ownerId===guest.id);
await Hub.leaveRoom(code,guest);
assert((await Hub.getSnapshot(code,owner)).room.screens.some(s=>s.ownerId===guest.id),'Screen must persist after changing rooms');
await Hub.act(code,guest,{type:'screen:heartbeat',sessionId:bScreen.sessionId});
await Hub.act(code,owner,{type:'screen:stop',sessionId:bScreen.sessionId});
assert(!(await Hub.getSnapshot(code,owner)).room.screens.some(s=>s.ownerId===guest.id));
const {code:empty}=await Hub.createRoom(owner,{name:'Expirável'});
await Hub.leaveRoom(empty,owner);
const now=Date.now;
try{Date.now=()=>now()+3600001;const cleaned=await Hub.cleanupExpired();assert(cleaned.removed>=1);await assert.rejects(Hub.joinRoom(empty,owner),/não encontrada|expirada/i)}finally{Date.now=now}
await Hub.act(code,owner,{type:'room:delete'});
await assert.rejects(Hub.getSnapshot(code,owner),/não encontrada/i);
console.log('✔ TDB 8.1: room permissions, 2×2 bots, spectator approval, solo training, music library, 3 screens, cross-room share, expiration, deletion');
// A player disconnects: game pauses, can resume, and eventually ends by abandonment.
const originalNow=Date.now,baseNow=Date.now();let future=baseNow;
try{
  Date.now=()=>future;
  const {code:reconnectCode}=await Hub.createRoom(owner,{name:'Teste de reconexão'});
  await Hub.joinRoom(reconnectCode,guest);
  const table=(await Hub.act(reconnectCode,owner,{type:'table:create',game:'chess',settings:{clock:300}})).table;
  await Hub.act(reconnectCode,guest,{type:'table:join',tableId:table.id});
  await Hub.act(reconnectCode,owner,{type:'table:start',tableId:table.id});
  future+=100000;
  await Hub.joinRoom(reconnectCode,owner);
  await Hub.getSnapshot(reconnectCode,owner,table.id);
  const Games=await import('../server/game-service.js');
  const pausedState=await Games.getGame(table.id);
  assert(pausedState.pausedAt,'game should pause for a disconnected player');
  future+=10000;
  const stillPaused=await Games.refreshGame(table.id);
  assert.deepEqual(stillPaused.clocks,pausedState.clocks,'chess clocks must not run while paused');
  await Hub.joinRoom(reconnectCode,guest);
  await Hub.getSnapshot(reconnectCode,guest,table.id);
  assert(!(await Games.getGame(table.id)).pausedAt,'game should resume on reconnection');
  future+=330000;
  await Hub.joinRoom(reconnectCode,owner);
  await Hub.getSnapshot(reconnectCode,owner,table.id);
  assert((await Games.getGame(table.id)).status==='abandoned','game should end by abandonment after reconnection window');
}finally{Date.now=originalNow}
console.log('✔ TDB 8.1: 3-minute reconnection, pause/resume and abandonment');
