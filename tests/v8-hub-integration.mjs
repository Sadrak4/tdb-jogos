/** TDB 8.0 social-room integration smoke. Runs locally without Supabase env. */
import assert from 'node:assert/strict';
import * as Hub from '../server/hub-service.js';
const ana={id:'TDB-A',username:'Ana'},bob={id:'TDB-B',username:'Bob'},other={id:'TDB-X',username:'Desconhecido'};
const created=await Hub.createRoom(ana,{name:'Sala da Galera',visibility:'public'});
const code=created.code;
assert.match(code,/^SALA-[A-F0-9]{8}$/);
assert.equal((await Hub.listRooms(ana))[0].name,'Sala da Galera');
await assert.rejects(Hub.getSnapshot(code,bob),/Entre nesta sala/);
await Hub.joinRoom(code,bob);
assert.equal((await Hub.getSnapshot(code,bob)).room.members.length,2);
await Hub.act(code,ana,{type:'message',message:'Olá, amigo!'});
assert.equal((await Hub.getSnapshot(code,bob)).messages[0].message,'Olá, amigo!');
await Hub.act(code,ana,{type:'music',action:{type:'add',url:'https://youtu.be/dQw4w9WgXcQ'}});
await Hub.act(code,bob,{type:'music',action:{type:'play'}});
let state=(await Hub.getSnapshot(code,ana)).room.music;
assert.equal(state.playing,true);
assert.equal(state.queue[0].videoId,'dQw4w9WgXcQ');
await Hub.act(code,ana,{type:'music',action:{type:'pause'}});
state=(await Hub.getSnapshot(code,ana)).room.music;
assert.equal(state.playing,false);
const ch=(await Hub.act(code,ana,{type:'table:create',game:'chess'})).table;
await Hub.act(code,bob,{type:'table:join',tableId:ch.id});
await Hub.act(code,ana,{type:'table:start',tableId:ch.id});
let snap=await Hub.getSnapshot(code,ana,ch.id);
assert.equal(snap.game.game,'chess');assert.equal(snap.game.board.length,8);
const player=snap.game.players.white.id===ana.id?ana:bob;
const move=await Hub.act(code,player,{type:'game:action',tableId:ch.id,action:{type:'MOVE',from:{r:6,c:4},to:{r:4,c:4},expectedVersion:snap.game.version}});
assert.equal(move.game.board[4][4].type,'pawn');
await assert.rejects(Hub.act(code,other,{type:'game:action',tableId:ch.id,action:{type:'RESIGN'}}),/Entre nesta sala/);
await Hub.act(code,ana,{type:'screen:start'});
const screen=(await Hub.getSnapshot(code,bob)).room.screen;
await Hub.act(code,ana,{type:'signal:send',to:bob.id,kind:'offer',sessionId:screen.sessionId,payload:{sdp:{type:'offer',sdp:'test'}}});
const signals=(await Hub.act(code,bob,{type:'signal:pull',after:0})).signals;
assert.equal(signals.length,1);assert.equal(signals[0].sender,ana.id);
await Hub.act(code,ana,{type:'screen:stop'});
assert.equal((await Hub.getSnapshot(code,bob)).room.screen,null);
await assert.rejects(Hub.act(code,ana,{type:'table:create',game:'pool'}),/Xadrez ou Truco/);
const tr=(await Hub.act(code,ana,{type:'table:create',game:'truco'})).table;
await Hub.act(code,bob,{type:'table:join',tableId:tr.id});
await Hub.act(code,ana,{type:'table:start',tableId:tr.id});
const truco=await Hub.getSnapshot(code,ana,tr.id);
assert.equal(truco.game.players.length,2);
const spect=await Hub.joinRoom(code,other).then(()=>Hub.getSnapshot(code,other,tr.id));
assert.equal(spect.game.role,'spectator');
for(const hand of Object.values(spect.game.hands))assert(hand.every(c=>c===null),'spectator cannot see cards');
await Hub.leaveRoom(code,bob);
assert.equal((await Hub.getSnapshot(code,ana)).room.members.length,2);
console.log('✔ v8 hub: auth membership, chat, music, 2 games, spectator privacy, screen signaling, leave');
