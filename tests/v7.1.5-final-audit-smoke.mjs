import fs from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const pkg=JSON.parse(read('package.json'));
const health=read('server/http-handlers/health.js');
const app=read('app.js');
const online=read('core/online-client.js');
const router=read('server/http-router.js');
const platform=read('core/platform-ui.js');
const admin=read('admin-panel.js');
const service=read('server/admin-service.js');
const css=read('ui/gameplay-fixes.css');
const chess=read('games/chess/chess.css');
const music=read('games/music/music.css');
const blackjack=read('games/blackjack/blackjack.css');
assert.equal(pkg.version,'7.1.5');
assert.match(health,/version:'7\.1\.5'/);
assert.match(app,/version:'7\.1\.5'/);
assert.match(online,/version:'7\.1\.5'/);
assert.match(router,/verifyAdminSession\(adminToken\)/);
assert.match(router,/x-tdb-admin-token/i);
assert.match(router,/allowAdminAccess!==false/);
assert.match(platform,/MODO MANUTENÇÃO ATIVO/);
assert.match(platform,/Acesso administrativo/);
assert.match(admin,/maintenanceReason/);
assert.match(admin,/Visualizar como usuário/);
assert.match(admin,/Abrir TDB como administrador/);
assert.match(service,/app:maintenance:internal/);
assert.match(service,/activatedBy/);
assert.match(css,/FINAL AUTHORITATIVE LAYOUT/);
assert.ok(chess.length>10000&&music.length>10000&&blackjack.length>10000);
console.log('v7.1.5 final audit: OK');
